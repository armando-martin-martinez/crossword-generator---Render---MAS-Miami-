"""Anonymous usage logging into public.play_events.

- Runs in a background thread: never delays the API response.
- Never raises: any failure is printed and swallowed, so gameplay is unaffected.
- Stores no IPs or emails. anon_id is a random per-browser UUID generated by the frontend.
"""
import os
import re
import threading

import psycopg2

_ANON_ID_RE = re.compile(r'^[A-Za-z0-9-]{8,64}$')
_HOST_RE = re.compile(r'^[a-z0-9.-]{1,253}$')


def clean_anon_id(value):
    return value if value and _ANON_ID_RE.match(value) else None


def clean_host(value):
    value = (value or '').strip().lower()
    return value if value and _HOST_RE.match(value) else None


def _insert(fields):
    conn = None
    try:
        conn = psycopg2.connect(os.getenv("DATABASE_URL"), connect_timeout=5)
        with conn, conn.cursor() as cur:
            cols = ', '.join(fields.keys())
            marks = ', '.join(['%s'] * len(fields))
            cur.execute(f"INSERT INTO play_events ({cols}) VALUES ({marks})", list(fields.values()))
    except Exception as e:
        print(f"⚠️ analytics: no se pudo registrar evento: {e}")
    finally:
        if conn is not None:
            conn.close()


_ALLOWED = {'event', 'anon_id', 'logged_in', 'topic', 'difficulty',
            'success', 'words_placed', 'duration_ms', 'ref_host'}


def log_event(event, **fields):
    """Fire-and-forget insert. Unknown keys are ignored; text values are capped at 64 chars."""
    row = {'event': event}
    for k, v in fields.items():
        if k in _ALLOWED and v is not None:
            row[k] = v[:64] if isinstance(v, str) else v
    threading.Thread(target=_insert, args=(row,), daemon=True).start()
